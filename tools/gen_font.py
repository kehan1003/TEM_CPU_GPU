def pack(rows):
    """7 行 x 5 列 -> 5 个列字节，bit0 是最上面一行。"""
    cols = []
    for c in range(W):
        b = 0
        for r in range(H):
            if rows[r][c] == "#":
                b |= 1 << r
        cols.append(b)
    return cols


def gen_js(path):
    """生成给 dashboard/index.html 用的字库表。"""
    out = []
    out.append("// 本文件由 tools/gen_font.py 生成，勿手工修改。")
    out.append("// 5x7 点阵字库，覆盖 ASCII 0x20..0x7F（0x7F 是度号 °）。")
    out.append("// 每个字符 5 个字节：一字节一列，bit0 为该列最上面的一行。")
    out.append("const MON_FONT5X7 = [")
    for code in range(0x20, 0x80):
        cols = pack(G.get(chr(code), ["....."] * 7))
        out.append("  [" + ",".join(f"0x{v:02X}" for v in cols) + f"],  // 0x{code:02X}")
    out.append("];")
    out.append("if (typeof module !== 'undefined') module.exports = MON_FONT5X7;")
    out.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {path}")


def gen_preview(path, scale=10):
    from PIL import Image, ImageDraw

    chars = [chr(c) for c in range(0x20, 0x80)]
    per_col = 8
    cols = (len(chars) + per_col - 1) // per_col
    cell_w, cell_h = W * scale + 24, H * scale + 26
    img = Image.new("RGB", (cols * cell_w, per_col * cell_h), (12, 16, 22))
    d = ImageDraw.Draw(img)
    for i, ch in enumerate(chars):
        cx = (i // per_col) * cell_w + 6
        cy = (i % per_col) * cell_h + 4
        rows = G.get(ch, ["....."] * 7)
        for r in range(H):
            for c in range(W):
                if rows[r][c] == "#":
                    d.rectangle([cx + c * scale, cy + r * scale,
                                 cx + c * scale + scale - 1, cy + r * scale + scale - 1],
                                fill=(226, 232, 240))
        label = repr(ch)[1:-1] or "SP"
        d.text((cx, cy + H * scale + 8), f"{ord(ch):02X} {label}", fill=(100, 116, 139))
    img.save(path)
    print(f"wrote {path}  {img.size}")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true", help="额外生成 tools/font_preview.png")
    ap.add_argument("--js", default=os.path.join(root, "dashboard", "font.js"))
    ap.add_argument("--png", default=os.path.join(root, "tools", "font_preview.png"))
    args = ap.parse_args()
    gen_js(args.js)
    if args.preview:
        gen_preview(args.png)


if __name__ == "__main__":
    main()
